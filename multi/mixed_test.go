// TestMixedPassage pins Segment's full token sequence on the passage above.
func TestMixedPassage(t *testing.T) {
	for i, c := range mixedPassage {
		got := Segment(c.in)
		if strings.Join(got, "|") != strings.Join(c.want, "|") {
			t.Errorf("line %d %q:\n  got  %v\n  want %v", i+1, c.in, got, c.want)
		}
	}
}

// TestMixedPassageAppendBytes: the []byte path agrees with Segment over the
// whole passage.
func TestMixedPassageAppendBytes(t *testing.T) {
	for _, c := range mixedPassage {
		want := strings.Join(Segment(c.in), " ")
		if got := string(AppendBytes(nil, c.in, ' ')); got != want {
			t.Errorf("AppendBytes(%q) = %q, want %q", c.in, got, want)
		}
	}
}

// TestNormalizeApplied: Segment normalizes input first, so the double-Sara-E
// misspelling "เเ" tokenizes identically to the correct "แ".
func TestNormalizeApplied(t *testing.T) {
	bad := Segment("เเปลกจริงๆ ที่เขาไม่มา") // เ + เ
	good := Segment("แปลกจริงๆ ที่เขาไม่มา") // แ
	if strings.Join(bad, "|") != strings.Join(good, "|") {
		t.Errorf("normalize not applied: %v vs %v", bad, good)
	}
	if len(bad) == 0 || bad[0] != "แปลก" {
		t.Errorf("expected first token %q, got %v", "แปลก", bad)
	}
}
